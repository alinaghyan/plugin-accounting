	public static function render( string $page ): void {
		$help = self::pages()[ $page ] ?? null;
		if ( ! $help ) {
			return;
		}
		echo '<div class="mda-help" dir="rtl"><span class="mda-help__icon" aria-hidden="true"><span class="dashicons dashicons-lightbulb"></span></span><div class="mda-help__body">';
		echo '<p>' . esc_html( $help['summary'] ) . '</p>';
		if ( ! empty( $help['fields'] ) ) {
			echo '<details><summary>' . esc_html__( 'راهنمای گزینه‌ها و فیلدها', 'malidev-accounting' ) . '</summary><dl>';
			foreach ( $help['fields'] as $term => $text ) {
				echo '<dt>' . esc_html( $term ) . '</dt><dd>' . esc_html( $text ) . '</dd>';
			}
			echo '</dl>';
			if ( ! empty( $help['tip'] ) ) {
				echo '<div class="mda-help__tip"><span class="dashicons dashicons-yes-alt" aria-hidden="true"></span><span>' . esc_html( $help['tip'] ) . '</span></div>';
			}
			echo '</details>';
		} elseif ( ! empty( $help['tip'] ) ) {
			echo '<div class="mda-help__tip"><span class="dashicons dashicons-yes-alt" aria-hidden="true"></span><span>' . esc_html( $help['tip'] ) . '</span></div>';
		}
		echo '</div></div>';
	}
